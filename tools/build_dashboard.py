"""Build the dashboard tab bundle from the shared web view. No npm needed.

    python tools/build_dashboard.py           write dashboard/dist/
    python tools/build_dashboard.py --check   fail if dashboard/dist/ is stale

The dist files are committed because Hermes installs plugins straight from
git and does not run a build step.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BANNER = "/* Generated by tools/build_dashboard.py. Edit web/ and dashboard/src/, then rebuild. */\n"


def outputs():
    read = lambda rel: (ROOT / rel).read_text(encoding="utf-8")
    return {
        ROOT / "dashboard/dist/index.js": BANNER + read("web/hermie-view.js") + "\n" + read("dashboard/src/tab.js"),
        ROOT / "dashboard/dist/style.css": BANNER + read("web/style.css"),
    }


def main(argv=None):
    check = "--check" in (sys.argv[1:] if argv is None else argv)
    stale = []
    for path, content in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print("wrote", path.relative_to(ROOT).as_posix())
    if stale:
        print("stale: " + ", ".join(stale) + " (run python tools/build_dashboard.py)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
